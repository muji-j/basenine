/**
 * 그 지표의 **화면 라벨**. ⚠**화면은 라벨 문자열을 직접 적지 않는다**(M1).
 *
 * ⚠**모르는 키에 던진다** — `denUnit` 과 같은 이유이고, 여기서는 **더 조용한 실패**를 막는다.
 * `term()` 은 라벨 → 키 역인덱스(`termKeyForLabel`)로 툴팁을 붙이는데, 그 역인덱스는
 * **모르는 라벨에 `undefined` 를 돌려주고 던지지 않는다.** 그래서 용어집의 라벨만 고치고
 * 화면의 하드코딩 문자열을 안 고치면 **툴팁이 소리 없이 사라진다** — 문법도 멀쩡하고
 * 글자도 나오므로 소스를 읽어서는 안 보인다.
 * → **라벨을 여기서 꺼내 쓰면 그 갈림 자체가 생기지 않는다.**
 *
 * ⚠**실제로 그 모양이 있었다**(2026-09-07): `連続安打` 가 `player-page`·`home-page`·`team-page`·
 * `blocks` 네 곳에 문자열로 박혀 있었고, 용어집 라벨은 그것과 별도로 존재했다.
 */
export function termLabel(key: string, table: Readonly<Record<string, Term>> = GLOSSARY): string {
  const t = table[key];
  if (t === undefined) {
    throw new Error(`용어집에 없는 지표: ${key} — glossary.ts 에 항목을 만들어라(M1)`);
  }
  return t.label;
}

/**
 * 화면 라벨 → 용어집 키.
 *
 * ⚠**이 역인덱스가 있어서 렌더러가 키를 따로 넘기지 않아도 된다.**
 * 라벨을 바꾸면 툴팁이 조용히 사라지므로, 「모든 용어가 라벨로 도달 가능한가」를 테스트가 고정한다.
 * ⚠`打率`와 `被打率`처럼 **뜻이 반대인 라벨을 같은 키로 묶지 마라.** 투수 화면이 타자 설명을 낸다.
 */
const BY_LABEL: Readonly<Record<string, string>> = Object.fromEntries(
  Object.entries(GLOSSARY).map(([key, t]) => [t.label, key]),
);

export function termKeyForLabel(label: string): string | undefined {
  return BY_LABEL[label];
}

