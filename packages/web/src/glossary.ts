export function termOf(key: string): Term | undefined {
  return GLOSSARY[key];
}

export function glossaryKeys(): string[] {
  return Object.keys(GLOSSARY);
}

/**
 * 화면 라벨 → 용어집 키.
 *
 * ⚠**이 역인덱스가 있어서 렌더러가 키를 따로 넘기지 않아도 된다.**
 * 라벨을 바꾸면 툴팁이 조용히 사라지므로, 「모든 용어가 라벨로 도달 가능한가」를 테스트가 고정한다.
 * ⚠`打率`와 `被打率`처럼 **뜻이 반대인 라벨을 같은 키로 묶지 마라.** 투수 화면이 타자 설명을 낸다.
 */
const BY_LABEL: Readonly<Record<string, string>> = Object.fromEntries(
  Object.entries(GLOSSARY).map(([key, t]) => [t.label, key]),
);

export function termKeyForLabel(label: string): string | undefined {
  return BY_LABEL[label];
}
