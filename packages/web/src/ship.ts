/**
 * **내보낼 때만 주석을 뗀다.**
 *
 * ⚠**소스의 주석은 이 저장소의 기억이다** — 왜 그렇게 했는지, 무엇을 이미 틀렸는지가 거기 있다.
 * 지우자는 게 아니라 **사용자에게까지 보낼 이유가 없다**는 것이다.
 *
 * ## 실측 (2026-08-31 · 이 기능을 만든 이유)
 *
 * | | 지금 | 주석 제거 | 절감 |
 * |---|---:|---:|---:|
 * | CSS 원본 | 168,770 B | 65,564 B | **−61.2%** |
 * | JS 원본 | 124,931 B | 70,241 B | −43.8% |
 * | **CSS brotli** | 44,792 B | 11,610 B | **−74.1%** |
 * | **JS brotli** | 38,645 B | 19,556 B | −49.4% |
 *
 * 압축 후에도 **첫 방문당 약 52KB** 가 준다(83KB → 31KB).
 * ⚠**압축 전 수치로 자랑하지 마라** — 사용자가 실제로 받는 것은 압축된 쪽이다.
 *
 * ## ⚠왜 블록 주석만 떼는가
 *
 * `//` 줄 주석은 **URL(`https://`)·정규식과 구별하려면 진짜 파서가 필요하다.**
 * 실측으로 이 파일의 `//` 형태는 **6곳뿐**이고 절감의 대부분은 블록 주석에 있다 —
 * **위험 대비 이득이 안 맞아서 안 건드린다.**
 *
 * ## ⚠안전한 이유 (실측)
 *
 * 문자열·정규식 안에 `/*` 나 `*​/` 가 들어 있으면 이 방식은 **코드를 잘라먹는다.**
 * 그래서 그걸 먼저 쟀다: 주석을 뗀 뒤 **남은 `/*` 0개 · 남은 `*​/` 0개**(CSS·JS 둘 다).
 * ⚠**그 측정은 「오늘」의 것이다** — 시험이 매번 다시 잰다(`ship.test.ts`).
 */

/**
 * 블록 주석을 뗀다. ⚠**여백은 안 건드린다** — 줄바꿈까지 지우면 이득은 조금인데
 * 「배포된 파일을 사람이 읽고 원인을 찾는」 길이 막힌다.
 */
export function stripBlockComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, "");
}

/**
 * 뗀 결과가 **원본과 같은 규칙을 갖는가.** 시험이 이걸 쓴다.
 *
 * ⚠**「길이가 줄었다」는 안전의 증거가 아니다** — 규칙을 하나 잘라먹어도 줄어든다.
 * 그래서 **선택자와 본문의 쌍**을 뽑아 통째로 비교한다.
 */
export function cssRules(css: string): string[] {
  const out: string[] = [];
  for (const m of stripBlockComments(css).matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    out.push(`${(m[1] ?? "").trim().replace(/\s+/g, " ")}{${(m[2] ?? "").trim().replace(/\s+/g, " ")}}`);
  }
  return out;
}
