/**
 * 강조 표기(`**…**`)를 **조각으로 나누는 규칙 한 벌**.
 *
 * ⚠**여기가 그 규칙의 정본이다**(M1). 이 프로젝트의 문구는 어디서나 별표 두 개로 강조를 쓰는데,
 * 그 규칙을 **아는 곳과 모르는 곳이 갈려 있었다**(2026-08-20 최종 검토 ①):
 * 서버의 `note()` 는 `<b>` 로 바꾸는데 **클라이언트의 용어 툴팁은 안 바꿔서**
 * 별표가 그대로 화면에 찍혔다 — 실측으로 용어집 **56항목 중 15항목**이 사용자 가시 문자열에
 * 별표를 갖고, 그중 하나 이상을 `data-term` 으로 노출하는 배포물이 **6,333 / 15,340장(41%)**.
 * 하필 「무엇을 재지 않는가」를 적은 문장들(`doused`·`gidp`·`winPct`·`twoStrike*`)만 골라 깨졌다.
 *
 * ⚠**이 함수는 자기 안에서 완결되어야 한다** — 바깥 이름을 하나도 참조하지 않는다.
 * 클라이언트는 서버 모듈을 import 할 수 없으므로 `assets.ts` 가 **이 함수의 소스를 그대로**
 * 클라이언트 스크립트에 심는다(`__EMPHASIS_PARTS__`). 바깥을 참조하면 그 자리에서 죽는다.
 * ⚠**백틱을 쓰지 마라** — 심는 곳이 백틱을 금지한다(`embedEmphasis` 가 던진다).
 */

/** 문장의 한 조각. `bold` 면 굵게 그린다 */
export interface EmphasisPart {
  text: string;
  bold: boolean;
}

/**
 * 별표 두 개로 감싼 곳을 골라낸다.
 *
 * ⚠**짝이 맞지 않으면 아무것도 하지 않는다.** 별표가 홀수 개면 어디까지가 강조인지 알 수 없고,
 * 그때 억지로 자르면 엉뚱한 곳이 굵어진다. 그 경우 **원문 그대로 한 조각**을 돌려준다 —
 * 즉 별표가 화면에 남는다. 그것이 「조용히 엉뚱한 곳을 굵게 하는 것」보다 낫고,
 * 남은 별표는 눈에 띄어 고쳐진다(M7 의 정신).
 */
export function emphasisParts(text: string): EmphasisPart[] {
  const parts = text.split("**");
  // 조각이 짝수 개 = 별표가 홀수 개 = 짝이 안 맞는다
  if (parts.length % 2 === 0) return [{ text: text, bold: false }];
  return parts.map((s, i) => ({ text: s, bold: i % 2 === 1 }));
}
