/**
 * 143試合換算.
 *
 * ⚠**완결 시즌에서 환산이 현재치보다 1 작았다**(2026-08-21 반증 라운드 확정).
 * 옛 식은 `Math.floor((count / teamGames) * games)` 였는데, 나눠서 생긴 이진수 오차가
 * 다시 곱해지면서 아래로 떨어졌다 — `(47 / 143) * 143 = 46.99999999999999` → **46**.
 * 배포물 108행 중 **5행**이 「現在 47 … 換算 46」이었다.
 *
 * ⚠**같은 행 안의 모순이라 눈에 띈다** — 값이 틀린 것보다 나쁜 자기모순이다.
 * ⚠**143 만의 문제가 아니다** — 11·13 의 배수 전반에서 나고 **2020(120경기)도 같은 결함**이다.
 * ⚠**기존 시험은 `pace` 를 픽스처에 손으로 박아** 이걸 구조적으로 못 잡았다.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { paceOf } from "../src/query.ts";

test("⚠시즌을 다 치른 선수의 환산은 현재치와 같다 — 한 행 안에서 모순이면 안 된다", () => {
  // 143경기 시즌을 전부 치렀다면 환산 = 현재치
  for (const count of [1, 11, 13, 47, 100, 143, 200]) {
    assert.equal(paceOf(count, 143, 2026), count, `143경기 완주인데 ${count} → ${paceOf(count, 143, 2026)}`);
  }
});

test("⚠2020 은 120경기다 — 그 시즌도 같은 규칙이어야 한다", () => {
  for (const count of [11, 13, 47, 120]) {
    assert.equal(paceOf(count, 120, 2020), count, `2020 120경기 완주인데 ${count} → ${paceOf(count, 120, 2020)}`);
  }
  // ⚠**143 으로 환산하면 안 된다** — 그 시즌에 존재하지 않는 기준이다.
  //   2020 에 60경기(절반)를 치르고 60개면, 그 시즌 기준 120경기 환산은 **120** 이다.
  //   143 기준이면 143 이 나온다 — 그 수가 나오면 시즌별 표를 안 보고 있다는 뜻이다.
  assert.equal(paceOf(60, 60, 2020), 120);
  assert.equal(paceOf(60, 60, 2026), 143, "2026 은 143경기 기준이어야 한다 — 두 시즌이 같은 수면 표를 안 본 것이다");
});

test("도중이면 남은 경기만큼 늘려서 환산한다", () => {
  // 71경기(≒절반)에 20홈런 → 143경기 환산 40
  assert.equal(paceOf(20, 71, 2026), 40);
  // 절반에 정확히 절반이면 두 배
  assert.equal(paceOf(50, 100, 2026), 71); // 50*143/100 = 71.5 → 71
});

test("⚠정수로 내림한다 — 홈런 「43.7본」은 존재하지 않는 수다", () => {
  assert.equal(paceOf(43, 140, 2026), 43); // 43*143/140 = 43.92…
  assert.ok(Number.isInteger(paceOf(43, 140, 2026)));
});

test("경기가 0이면 0이다 — 나누지 않는다(M11 의 정신: 지어내지 않는다)", () => {
  assert.equal(paceOf(10, 0, 2026), 0);
  assert.equal(paceOf(10, -1, 2026), 0);
});
