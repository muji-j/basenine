/**
 * **선수 페이지를 어느 쪽으로 그릴 것인가**(`roleOf`).
 *
 * ⚠**이 판정이 틀리면 화면이 반대편을 그린다.** 투수를 타자로 판정하면 자기 타석이 0이라
 * 스플릿이 통째로 「打席がありません」이 된다 — **에러가 아니라 빈 화면**이라
 * 아무도 결함으로 못 읽는다. 실제로 오래 그 상태였다.
 *
 * ## 실측 (2026-08-27 · 보유 9시즌)
 *
 * - 투타 양쪽 기록을 가진 **2,374 선수-시즌** 중 **917 이 `position` 미상**이었고
 *   그만큼 투수 스플릿이 사라졌다 — **상대한 타자 합 163,631 · 한 명 최대 847**.
 *   소급 시즌일수록 심했다: **2018년 191명 · 2026년 0명**.
 * - 명단(`roster.html`)의 포지션 구획으로 **829명 전원**을 메웠고, 선수 페이지에도 값이 있던
 *   **811명과 대조해 808 일치**(불일치 3은 전부 전향·그 경기 시점 표기).
 * - 메운 **뒤에도** 남는 것이 **4건이고 전부 한 사람**이다(西純 · 2021~2024) —
 *   `position` 이 **현재**를 말하기 때문이다. 그래서 그 시즌 데이터가 마지막 말을 한다.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { roleOf } from "../src/query.ts";

/** ⚠가장 강한 근거. 대부분이 여기서 갈린다 */
test("포지션이 투수면 투수다", () => {
  assert.equal(roleOf({ position: "投手", batterPa: 30, pitcherBf: 0 }), "pitcher");
});

/** ⚠퍼시픽 투수는 자기 타석이 없다 — 「타격 기록 없음」과 「0타석」은 다르다(M11) */
test("타격 기록이 아예 없고 투구 기록이 있으면 투수다", () => {
  assert.equal(roleOf({ position: null, batterPa: null, pitcherBf: 186 }), "pitcher");
});

/**
 * ⚠**포지션이 미상이어도 옳게 그린다.**
 * 실측 예: ケラー(2025) — `position` 미상 · 상대 타자 **186** · 자기 타석 **0**.
 * 옛 판정은 여기서 **타자**를 냈고 스플릿이 통째로 사라졌다.
 */
test("⚠포지션이 미상이어도 투구가 본업이면 투수다 — 917 선수-시즌이 이 자리였다", () => {
  assert.equal(roleOf({ position: null, batterPa: 0, pitcherBf: 186 }), "pitcher");
});

/**
 * ⚠**포지션이 「현재」를 말하므로 전향을 못 따라간다.**
 * 실측 예: 西純(2022) — 지금은 `外野手` 인데 그 시즌 상대 타자 **336** · 자기 타석 **27**.
 */
test("⚠전향한 선수도 투수였던 시즌은 투수로 그린다", () => {
  assert.equal(roleOf({ position: "外野手", batterPa: 27, pitcherBf: 336 }), "pitcher");
});

/**
 * ⚠**반대 방향을 망가뜨리지 않는다** — 야수 등판은 여전히 타자다.
 * 실측 5건: 北村 6대132 · オスナ 2대226 · 増田大 3대50 · 柴田 1대14 · 北村(2023) 4대38.
 * ⚠**이 다섯이 「지금 판정이 맞는 쪽」이다** — 고치다가 이쪽을 뒤집으면 결함을 옮긴 것이다.
 */
test("⚠야수 등판은 타자로 남는다 — 고치다가 반대편을 뒤집지 않는다", () => {
  for (const [bf, pa, who] of [[6, 132, "北村2025"], [2, 226, "オスナ2026"], [3, 50, "増田大2020"],
    [1, 14, "柴田2026"], [4, 38, "北村2023"]] as const) {
    assert.equal(
      roleOf({ position: "内野手", batterPa: pa, pitcherBf: bf }),
      "batter",
      `${who}(상대 ${bf} · 자기 ${pa})가 투수로 판정됐다`,
    );
  }
});

/** ⚠투구 기록이 없으면 볼 것도 없다 */
test("투구 기록이 없으면 타자다", () => {
  assert.equal(roleOf({ position: null, batterPa: 500, pitcherBf: null }), "batter");
  assert.equal(roleOf({ position: "内野手", batterPa: 0, pitcherBf: null }), "batter");
});

/**
 * ⚠**동수는 타자로 둔다.** 억지 규칙이 아니라 **기존 거동을 안 바꾸는 쪽**이다 —
 * 옛 판정도 이 경우 타자였다. 실측에서 동수는 0건이라 값에는 영향이 없고,
 * **경계를 적어 두는 것 자체**가 다음 사람이 뒤집지 않게 한다.
 */
test("⚠동수면 타자다 — 경계를 못 박는다", () => {
  assert.equal(roleOf({ position: null, batterPa: 10, pitcherBf: 10 }), "batter");
});
