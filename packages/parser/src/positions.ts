/**
 * 포지션 어휘 — `投手`·`捕手`·`内野手`·`外野手` 4종. **한 벌만 둔다**(M1).
 *
 * npb.jp 의 **서로 다른 두 페이지**가 같은 4종을 쓴다 — 경기별 명단(`roster.html`)의
 * 구획 머리와 드래프트 명단(`draftlist_{team}.html`)의 포지션 칸.
 * 2026-09-05 에 드래프트 파서가 어휘를 **한 벌 더 선언**했다(실측: 타입도 조회표도
 * 문자 단위로 동일했고, 다른 것은 타입 이름뿐이었다). **값이 같아서 기능은 멀쩡했다** —
 * 그래서 시험도 타입체크도 아무 말을 하지 않았고, **한쪽만 고쳐지는 날 조용히 갈린다.**
 * 이 저장소가 M1 을 세운 근거가 바로 그 사고다(구 PPS 의 파서 3중 구현).
 *
 * ## ⚠왜 여기인가 — 고르지 않은 자리와 그 이유를 남긴다
 *
 * 다음 사람이 같은 저울질을 처음부터 다시 하지 않도록 적어 둔다.
 *
 * - **`roster.ts` 에 두고 `draft.ts` 가 가져가기** — 드래프트 지명은 경기 명단과
 *   아무 상관이 없다. 그 화살표는 **없는 관계를 만들고**, `roster.ts` 가 `player.ts` 를
 *   가져가므로 드래프트 파서가 **쓰지도 않는 의존을 물려받는다.**
 * - **`tokens.ts`** — 그 파일은 **타석 결과 셀 전용**이다(export 7건이 전부
 *   `Outcome`/`PaResult` 계열). 스스로를 「지표 입력의 원천 · 가장 깨지기 쉬운 지점」이라고
 *   선언한 파일이라, 상관없는 어휘를 얹으면 **그 선언이 헐거워진다.**
 * - **`@bb-app/domain`** — 지금 담고 있는 것이 팀·색·구장이다. 그리고 여기 고정하는 것은
 *   야구의 포지션 개념이 아니라 **「npb.jp 가 이 두 페이지에 쓰는 낱말」**이라 파서 쪽 사실이다.
 *   npb.jp 밖의 소스가 같은 어휘를 요구하는 날 그때 올린다.
 *
 * ⚠**이 파일은 아무것도 import 하지 않는다.** 잎으로 두면 순환이 **구조적으로** 불가능하다.
 *
 * ## ⚠정규화는 여기 두지 않는다 — 공유하는 것은 어휘이지 읽는 법이 아니다
 *
 * 두 파서가 **다르게** 정규화하고, 다른 것이 맞다:
 *   - 명단은 구획 머리를 **그대로** 쓴다(`trim` 만).
 *   - 드래프트는 **NFKC + 공백 제거**를 건다 — 2006 의 `投　手` 를 2019 의 `投手` 와
 *     같은 자리로 보내야 하기 때문이다.
 * 여기에 정규화를 얹어 「한 벌」로 만들면 **명단 파서의 동작이 조용히 바뀐다.**
 * 두 벌인 것이 결함인 것과, 두 벌이어야 하는 것을 구별해라.
 */

/**
 * 포지션 4종.
 *
 * ⚠**`player.ts` 의 `position` 은 이 타입이 아니다** — 선수 페이지 값은 원문 그대로 두는
 * `string | null` 이고 **그건 의도다.** 그 칸은 「등 원문」이라 어휘가 닫혀 있지 않다.
 * 닫히지 않은 값을 닫힌 타입으로 좁히면 **모르는 표기가 생긴 날 조용히 거짓이 된다.**
 */
export type Position = "投手" | "捕手" | "内野手" | "外野手";

/**
 * 어휘 조회표. 모르는 값은 `undefined` 가 되고, **호출자가 그것을 실패로 만든다**(M7).
 *
 * ⚠**키가 `string` 인 것이 요점이다.** `Record<Position, Position>` 으로 좁히면
 * 「어휘 밖인가」를 물을 수 없게 되고 — 물을 수 없으면 검증 자체가 사라진다.
 * 이 표의 존재 이유는 매핑이 아니라 **판정**이다.
 */
export const POSITIONS: Readonly<Record<string, Position>> = {
  投手: "投手",
  捕手: "捕手",
  内野手: "内野手",
  外野手: "外野手",
};
