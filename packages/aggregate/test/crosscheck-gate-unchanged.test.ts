/**
 * ⚠**공표표 해석이 던지면 관문은 지금처럼 그대로 죽는다**(잡히지 않은 예외 → 종료 1).
 * 감지 모드(`--emit`)만 그것을 `table_parse_error` 로 잡는다(설계 D2) — **관문 경로가 따라 잡기 시작하면**
 * 덤프의 첫 줄(던진 자리)이 파서가 아니라 도구가 되고 · 종료코드가 갈린다.
 */
const THROWS: readonly { name: string; opts: ScenarioOptions; message: RegExp }[] = [
  {
    name: "성적표 헤더가 바뀌었다(타격표 열 순서)",
    opts: { broken: ["idb1_c"] },
    message: /StatsParseError: 타격 성적표의 헤더가 예상과 다르다/,
  },
  {
    name: "한 장 안에 「現在」 날짜가 둘이다",
    opts: { asOf: (t) => (t === "idb1_t" ? ["2026-09-28", "2026-09-27"] : AS_OF) },
    message: /StatsParseError: 공표표의 기준일이 서로 다른 것이 둘 이상이다/,
  },
];

for (const c of THROWS) {
  test(`⚠관문 — ${c.name}: 지금처럼 잡히지 않은 예외로 종료 1 · stdout 없음 · 던진 자리는 파서다`, () => {
    const s = buildScenario(c.opts);
    try {
      const r = runTool(s);
      assert.equal(r.code, 1, "관문 종료코드가 바뀌었다");
      assert.equal(r.stdout, "", "관문이 죽기 전에 무언가를 찍었다 — 예외를 잡고 계속 간 것이다");
      assert.match(r.stderr, c.message, "던진 예외가 덤프에 없다");
      const first = r.stderr.split(/\r?\n/, 1)[0] ?? "";
      assert.match(
        first,
        /\/packages\/parser\/src\/stats\.ts:\d+$/,
        `덤프의 첫 줄(던진 자리)이 파서가 아니다 — 도구가 예외를 잡아 다시 던졌다: ${first}`,
      );
    } finally {
      s.cleanup();
    }
  });
}
