-- 020 입찰이 **선언한 경합 상대**를 담는다.
--
-- ⚠**019 는 손대지 않는다** — 실 DB(`data/bb.sqlite`)에 이미 적용돼 있다
--   (2026-09-04T16:49:57Z · `schema_migration` 실측). 019 를 고치면 그 DB 에서는
--   영영 안 돌고, 새로 만든 DB 와 스키마가 갈린다.
--
-- ## 왜 필요한가 — 「단독지명」이라는 거짓 사실이 만들어지는 것을 막는다
--
-- ⚠**단독지명은 어느 소스도 적지 않는다.** 적재가 **경합 그룹의 여집합**으로 유도한다
--   (`store/src/draft.ts`). 그래서 **경합 주석 하나가 조용히 안 읽히면 그 구단의 1巡目이
--   「아무도 안 겹쳤다」로 둔갑한다** — 값도 합계도 그럴듯해서 눈으로는 못 잡는다.
--   실제로 파서가 그렇게 될 수 있었다(2026-09-05 최종 검토 [I1] · 변종 4건이 조용히 0건).
--
-- ⚠**그때 DB 가 모순을 드러내려면 「몇 구단이 겹쳤어야 하는가」를 알아야 한다.**
--   그것을 아는 유일한 자료가 주석의 상대 구단 목록(`DraftBidRow.rivals`)인데,
--   **적재가 그 필드를 한 번도 읽지 않았다**(비테스트 소비자 0건 · 같은 검토의 [I2]).
--   담으면 「奥川 그룹은 3구단이어야 하는데 2구단뿐」이 **모순으로 드러난다.**
--
-- ## 담는 형태
--
-- `rivals` 는 **소스 표기 그대로의 JSON 배열**이다(`["東京ヤクルト","阪神"]`).
-- ⚠**구단 코드로 바꾸지 않는다.** 이 표기는 `TEAMS`(`東京ヤクルトスワローズ`)와도
--   `SHORT_NAME`(`ヤクルト`)과도 다른 **세 번째 어휘**라 새 매핑표가 필요한데,
--   그건 이름 규칙을 한 벌 더 만드는 것이라 **M1 위반**이다. 게다가 2001~2007 에는
--   `近鉄`·`ブルーウェーブ` 처럼 **현행 12구단 표에 없는 구단**이 나와서, 지금 코드로 바꾸면
--   그 해의 경합이 **던지거나 조용히 사라진다.** 원문 보존이 더 싸고 되돌릴 수 있다.
--
-- ⚠**`NULL` 은 「원래 없음」이다**(M11) — 유도한 단독지명 행에는 주석 자체가 없다.
--   `'[]'`(주석은 있는데 상대가 0개)와 **다른 값**이고, 파서가 `'[]'` 를 낼 수는 없다
--   (`(.+?)と重複` 이라 상대가 최소 1건이다).
--
-- ⚠**CHECK 는 한 방향만 건다**: 「그룹에 안 속하는데(=단독) 상대를 주장한다」만 막는다.
--   반대 방향(그룹에는 속하는데 `rivals` 가 NULL)은 **막지 않는다** — wikipedia 처럼
--   그리드로 그룹을 알려 주면서 상대 이름 문장은 없는 소스가 실재할 수 있고,
--   그건 결함이 아니라 **「그 소스는 안 말한다」**(M11)다. 그 행은 아래 불변식에서
--   **위반이 아니라 분모 밖**으로 빠진다.
--   ⚠**SQLite 는 `ALTER TABLE ADD COLUMN` 의 CHECK 를 기존 행에 소급 적용하지 않는다.**
--     지금은 `draft_bid` 가 0행이라 무해하다(2026-09-05 실측).

ALTER TABLE draft_bid ADD COLUMN rivals TEXT
  CHECK (
    (rivals IS NULL OR json_valid(rivals))
    AND (group_key IS NOT NULL OR rivals IS NULL)
  );
