-- 대회 표기 원문.
--
-- ⚠**이것이 없어서 포스트시즌이 정규시즌에 섞여 있었다.** 구단 코드로는 구별할 수 없다 —
-- CS도 일본시리즈도 같은 구단 코드를 쓴다. 실측(2026-08-16): 2025년 아카이브를 채운 직후
-- 「정규시즌」이 904경기가 됐고, 그 안에 **CS 13경기와 일본시리즈 5경기**가 들어 있었다.
-- 빼면 실시 858경기 = NPB 정규시즌 경기 수(143×12÷2)와 정확히 일치한다.
--
-- ⚠**`competition`(판정 결과)과 `series`(원문)를 둘 다 든다**(M4).
-- 판정 규칙이 바뀌었을 때 「원본이 뭐라고 썼는가」로 되돌아갈 수 있어야 한다.
-- 표기에는 후원사 이름이 붙어 해마다 바뀐다(`JERA` · `パーソル` · `日本生命` · `SMBC`).
--
-- ⚠**交流戦은 `competition = 'regular'`다.** 정규시즌 경기이고 리그 순위에 그대로 들어간다.
-- 원문(`日本生命セ・パ交流戦`)은 이 열에 남으므로, 나중에 교류전만 따로 보는 것도 가능하다.

ALTER TABLE game ADD COLUMN series TEXT;

-- 시즌 집계는 거의 전부 `competition`으로 거른다. 포스트시즌이 들어온 뒤로 이 필터가
-- 실제로 행을 걸러내게 됐으므로 색인을 붙인다.
CREATE INDEX IF NOT EXISTS game_by_competition ON game (season, competition, game_date);
