-- 018 시즌별 표시명
--
-- ⚠**표시명이 「아카이브 최초 등장 경기」의 이름으로 영구 고정돼 있었다**
-- (2026-08-21 다방면 감사 확정 P1). `load-archive.ts` 가 `seenPlayers` 로 첫 접촉에만
-- `upsertPlayer` 를 부르는데, 순회가 **날짜 오름차순**이라 첫 접촉 = 가장 오래된 경기다.
-- 그래서 `player.display_name` 의 주석(「최신 표기」)이 코드와 정반대였다.
--
-- 실측(감사 · 아카이브 box 7,805장 전수 재파싱): DB 이름이 **최초 이름과 1,640/1,640 일치** ·
-- **최종 이름과는 1,531/1,640** → 드리프트 **109명(6.6%) 전원이 옛 이름**.
-- 배포물 **12,862/15,439장(83.3%)** 이 그 109명 중 최소 한 명을 옛 이름으로 그렸다.
-- 실제 피해: 2026 화면에 `石川` 이 **두 사람** 나온다(NPB 는 그 해 `石川慎`/`石川柊` 로 구별한다) —
-- **충돌은 우리가 만든 것**이다.
--
-- ## ⚠「최신이 이긴다」로 고치지 않는다
--
-- NPB 박스 표기는 「신·구 등록명」이 아니라 **그 시점의 로스터 식별 표기**다. 방향이 양쪽이고
-- (늘어남 55 · 줄어듦 44 · 무관 10 — `松井雅→松井` · `山田哲→山田`), 감사 실측으로
-- **최종 고정은 최초 고정보다 오히려 나쁘다**(620쌍 중 틀린 것 298 → 327).
-- 옳은 것은 **그 시즌 화면에는 그 시즌의 이름**이다.
--
-- ## 이 표가 하는 일
--
-- `player.display_name` 은 **그대로 둔다** — 시즌을 가리지 않는 자리(검색 색인·통산표)가 쓴다.
-- 시즌 화면은 여기를 먼저 보고, 없으면 그쪽으로 떨어진다.
--
-- ⚠**재수집이 필요 없다.** 이름은 이미 받아 둔 박스스코어 안에 있고, 적재가 첫 경기 것만
-- 쓰고 나머지를 버리고 있었을 뿐이다. 외부 요청 **0회**로 채워진다.
CREATE TABLE player_season_name (
  player_id    TEXT    NOT NULL REFERENCES player (player_id),
  season       INTEGER NOT NULL,
  display_name TEXT    NOT NULL,
  -- M4: 어디서 · 언제 · 무엇 기준인가.
  -- ⚠`as_of` 는 **그 이름을 쓴 경기의 경기일**이다(적재 시각이 아니다). 이것이 정본 선택의 근거다 —
  --   같은 시즌 안에서 표기가 흔들리면 **가장 나중 경기의 표기**를 그 시즌의 이름으로 본다.
  -- ⚠**적재 순서에 의존하지 않는다**(M5). 아래 UPSERT 가 `as_of` 로 비교하므로
  --   `--from` 으로 중간부터 다시 돌려도 결과가 같다.
  as_of        TEXT    NOT NULL,
  source       TEXT    NOT NULL,
  PRIMARY KEY (player_id, season)
) STRICT;

-- 시즌 화면이 매번 이 표를 통째로 읽는다(선수 한 명씩 찾지 않는다).
CREATE INDEX IF NOT EXISTS player_season_name_season ON player_season_name (season);
