-- 009 읽는 법과 등번호
--
-- ⚠**재수집이 필요 없다.** 두 값 모두 이미 받아 둔 선수 페이지 858장의 표제부(`#pc_vitals`)에
-- 들어 있었고, 파서가 프로필 표(`#pc_bio`)만 읽고 있어서 매번 버려졌다(2026-08-17 확인).
-- 외부 요청 **0회**로 채워진다.
--
-- ⚠**검색은 이 두 값 없이는 한자 표기 하나로만 좁혀진다.** 「たかはし」로도 「34」로도
-- 찾을 수 없는 것이 지금 상태다.

-- 읽는 법. **원문 그대로 넣는다**(M4).
-- ⚠「히라가나」라고 부르지 않는다 — 실측 858장 중 737장이 `たかはし・こうや` 꼴이지만
-- **121장은 외국인 선수라 `ルーク・ボイト (LUKE VOIT)` 꼴**이다. 히라가나로 정규화하면
-- 그 121명의 검색어가 사라진다. 해석은 화면의 검색 색인이 한다.
ALTER TABLE player ADD COLUMN kana TEXT;

-- 등번호. **TEXT다** — NPB에 `00`이 실재하고, 정수로 바꾸면 `0`과 구별할 수 없다.
-- ⚠**NULL은 「0번」이 아니라 「지금 등록이 없다」**(M11). 실측 858명 중 76명이 이 항목 자체가
-- 없고, 그 76명은 **2026시즌 출장이 0**이다(은퇴·이적). 0으로 채우면 은퇴 선수가 전원 0번이 된다.
ALTER TABLE player ADD COLUMN uniform_number TEXT;
